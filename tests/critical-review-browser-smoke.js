async (existingPage) => {
  const context=await existingPage.context().browser().newContext();
  const page=await context.newPage();const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  const ready=()=>page.waitForFunction(()=>document.documentElement.dataset.reviewReady==='true');
  const url=new URL('critical-review.html',existingPage.url()).href;
  try {
    await page.goto(existingPage.url());
    await page.waitForFunction(()=>document.documentElement.dataset.appReady==='true');
    await page.getByRole('link',{name:'Critical review',exact:true}).click();await ready();
    const totals=await page.locator('#review-status').evaluate(el=>({...el.dataset}));
    assert(totals.tables==='9'&&totals.total==='836'&&totals.unavailable==='0','Manifest coverage missing');
    assert(await page.locator('.review-result').count()===836,'Not all cells rendered');
    assert(await page.locator('.review-green').count()===Number(totals.green),'Green counts inconsistent');
    assert(await page.locator('.review-yellow').count()===Number(totals.yellow),'Yellow counts inconsistent');
    assert(await page.locator('#review-overview a').count()===9,'Overview incomplete');
    const colors=await page.evaluate(()=>Object.fromEntries(['green','yellow'].map(key=>[key,getComputedStyle(document.querySelector('.review-'+key)).backgroundColor])));
    assert(colors.green==='rgb(220, 239, 226)'&&colors.yellow==='rgb(255, 240, 180)','Actual cell colors missing');
    assert((await page.locator('.review-yellow').first().textContent()).includes('Yellow: needs review'),'No accessible status text');
    assert(await page.locator('.review-yellow').first().locator('li').count()>0,'No visible reason');
    assert((await page.locator('.review-guide').textContent()).includes('NOT mean verified'),'Green disclaimer missing');
    const reports=[];
    for(const viewport of [{width:1280,height:900},{width:375,height:812}]) {
      await page.setViewportSize(viewport);
      await page.locator('#review-table').selectOption('A-10.10.1');
      await page.waitForFunction(()=>location.hash==='#A-10.10.1'&&document.querySelectorAll('.review-result').length===95);
      assert(await page.locator('#review-results section').count()===1,'Selector did not isolate table');
      await page.locator('#review-filter').selectOption('yellow');
      assert(await page.locator('.review-green').count()===0,'Yellow filter leaves green');
      assert(await page.locator('.review-yellow').count()>0,'Yellow results absent');
      await page.locator('#review-filter').selectOption('green');
      assert(await page.locator('.review-yellow').count()===0&&await page.locator('.review-green').count()>0,'Green filter mismatch');
      await page.locator('#review-filter').selectOption('yellow');
      await page.locator('#review-reason').selectOption('duration');
      assert(await page.locator('.review-result').count()>0,'Duration examples absent');
      assert(await page.locator('.review-result').evaluateAll(cells=>cells.every(c=>c.dataset.reasons.split(' ').includes('duration'))),'Reason filter mismatch');
      await page.locator('#review-search').fill('no-such-result-938475');
      assert(await page.locator('.review-result').count()===0,'Empty search should not show cells');
      assert((await page.locator('#review-match-count').textContent()).startsWith('0 matching'),'Empty count wrong');
      await page.locator('#review-search').fill('');await page.locator('#review-reason').selectOption('all');await page.locator('#review-filter').selectOption('all');
      const original=await page.locator('.original').first().textContent();
      await page.getByRole('checkbox',{name:'Use emojis',exact:true}).check();
      assert(await page.locator('.critical-token[role="img"]').count()>0,'Emoji preference not applied');
      const icons=await page.locator('.critical-token[role="img"]').evaluateAll(elements=>elements.map(el=>el.firstChild.textContent.trim()));
      assert(icons.every(icon=>['💥','🌀','🚫','🌀🚫','🛡️','🩸','➖','➕'].includes(icon)),'Review has an obsolete effect icon');
      const parry=page.locator('.critical-token[aria-label^="Must parry:"][aria-label*=" at −"]').first();
      assert(await parry.count()>0,'Missing real parry penalty example');
      assert(await parry.evaluate(el=>el.firstChild.textContent.trim())==='🛡️','Parry penalty icon must be only a shield');
      assert((await parry.textContent()).includes('at −15'),'Numeric must-parry penalty lost');
      assert(await page.locator('.original').first().textContent()===original,'Original source changed with presentation');
      await page.getByRole('checkbox',{name:'Use emojis',exact:true}).uncheck();
      assert(await page.locator('.critical-token[role="img"]').count()===0,'Bold mode not restored');
      assert(await page.locator('.critical-token').count()>0,'Readable bold output absent');
      const scroll=page.locator('.review-scroll').first();
      const dims=await scroll.evaluate(el=>({width:el.clientWidth,total:el.scrollWidth,page:document.documentElement.scrollWidth,viewport:innerWidth}));
      assert(dims.total>dims.width,'Review table must scroll horizontally');
      assert(dims.page<=dims.viewport,'Review overflows mobile page');
      await scroll.focus();await page.keyboard.press('ArrowRight');
      await page.waitForFunction(()=>document.querySelector('.review-scroll').scrollLeft>0);
      reports.push({viewport,filters:true,originalAndReadable:true,horizontalScroll:true,noPageOverflow:true});
    }
    await page.getByRole('checkbox',{name:'Use emojis',exact:true}).check();
    await page.reload();await ready();
    assert(await page.getByRole('checkbox',{name:'Use emojis',exact:true}).isChecked(),'Preference not persisted');
    assert(await page.locator('.critical-token[role="img"]').count()>0,'Persisted mode not rendered');
    await page.getByRole('checkbox',{name:'Use emojis',exact:true}).uncheck();
    assert(await page.locator('#review-table').inputValue()==='A-10.10.1','Shareable hash not restored');
    await page.locator('#review-table').selectOption('all');await page.waitForFunction(()=>document.querySelectorAll('.review-result').length===836);
    await page.route('**/tables/A-10.10.1.json',route=>route.fulfill({status:404,body:'Not found'}));
    await page.locator('#review-retry').click();await ready();
    assert((await page.locator('#review-status').textContent()).includes('1 unavailable'),'Missing table not reported');
    assert(await page.locator('.review-error').count()>0,'Missing table must have yellow warning');
    assert((await page.locator('#review-match-count').textContent()).includes('incomplete'),'Partial totals misleading');
    await page.unroute('**/tables/A-10.10.1.json');await page.locator('#review-retry').click();await ready();
    assert(await page.locator('.review-result').count()===836,'Retry did not recover all tables');
    await page.route('**/tables/index.json',route=>route.fulfill({status:200,contentType:'application/json',body:'[]'}));
    await page.locator('#review-retry').click();await page.waitForFunction(()=>document.documentElement.dataset.reviewReady==='error');
    assert(await page.locator('.review-result').count()===0,'Empty manifest falsely reports checked cells');
    assert((await page.locator('#review-status').textContent()).includes('No critical-strike tables'),'Empty manifest explanation absent');
    await page.unroute('**/tables/index.json');
    await page.route('**/tables/index.json',route=>route.fulfill({status:503,body:'Unavailable'}));
    await page.locator('#review-retry').click();await page.waitForFunction(()=>document.documentElement.dataset.reviewReady==='error');
    assert((await page.locator('#review-status').textContent()).includes('503'),'Manifest error not explained');
    await page.unroute('**/tables/index.json');await page.locator('#review-retry').click();await ready();
    await page.getByRole('link',{name:'← Rolemaster Fieldbook'}).click();
    await page.waitForFunction(()=>document.documentElement.dataset.appReady==='true');
    assert(await page.getByRole('link',{name:'Critical review',exact:true}).count()===1,'Return navigation broken');
    assert(errors.length===0,errors.join('\n'));
    return {url,totals,colors,desktopMobile:reports,shareable:true,missingTable:'recovered',emptyManifest:'explained',manifestFailure:'recovered',pageErrors:0};
  } finally {await context.close();}
}
